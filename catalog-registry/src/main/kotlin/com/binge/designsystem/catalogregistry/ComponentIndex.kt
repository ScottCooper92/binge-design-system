@file:JvmName("ComponentIndexGenerator")

package com.binge.designsystem.catalogregistry

import java.io.File
import kotlin.system.exitProcess

/** A group in the index: the `@group` key a KDoc names, and the heading it appears under. */
data class IndexGroup(
    val key: String,
    val heading: String,
) {
    companion object {
        val Screens = IndexGroup("screens", "Screens and scaffolds")
        val Bars = IndexGroup("bars", "Bars")
        val Sheets = IndexGroup("sheets", "Sheets and pickers")
        val Rows = IndexGroup("rows", "Rows and lists")
        val Cards = IndexGroup("cards", "Cards and tiles")
        val Media = IndexGroup("media", "Media and carousels")
        val Inputs = IndexGroup("inputs", "Inputs")
        val Feedback = IndexGroup("feedback", "Feedback and state")
        val Detail = IndexGroup("detail", "Detail pages")
        val Tv = IndexGroup("tv", "TV")

        /** This repository's groups, in the order the index lists them. */
        val DesignSystem = listOf(Screens, Bars, Sheets, Rows, Cards, Media, Inputs, Feedback, Detail, Tv)
    }
}

/** What a `@sample` tag, and a sample found without one, names: a `@Composable fun …Sample()` in the catalog sources, or a class there. */
enum class SampleKind { Functions, Classes }

/**
 * What differs between repositories that share this generator. The tag grammar never does: `@need`, `@group`, `@replaces`, `@sample`.
 *
 * @property groups the `@group` keys a KDoc may name, with the heading each is listed under, in listing order.
 * @property sampleKind what the sample sources declare: composable functions named `…Sample`, or classes.
 * @property includeHelpers also lists a class, object, interface, non-composable function or lowercase composable whose KDoc carries
 *   `@need`. One without `@need` is never a problem; a capitalised public composable without it always is.
 * @property moduleColumn adds a column naming each entry's module, the first path segment of its file.
 * @property title, intro, generatedNote the page's heading, the paragraph under it and the comment above it.
 */
data class IndexConfig(
    val groups: List<IndexGroup> = IndexGroup.DesignSystem,
    val sampleKind: SampleKind = SampleKind.Functions,
    val includeHelpers: Boolean = false,
    val moduleColumn: Boolean = false,
    val title: String = "Component index",
    val intro: List<String> =
        listOf(
            "Find a component by what you need, not by its name. Each row gives the component, what it is, the catalog",
            "sample to copy and what it replaces. If a need is not here, check `catalog/` before building one in an app.",
        ),
    val generatedNote: List<String> =
        listOf(
            "<!-- Generated by :catalog-registry (./gradlew generateComponentIndex) from the @need, @group and @replaces -->",
            "<!-- tags in each public composable's KDoc. Do not edit; change the KDoc and regenerate. -->",
        ),
)

/** One public composable (or, with [IndexConfig.includeHelpers], one helper) as the index lists it. */
data class IndexEntry(
    val name: String,
    val group: IndexGroup,
    val need: String,
    val replaces: String?,
    val description: String,
    val sample: String?,
    val module: String = "",
)

/** What one file contributed to the index, and what it could not. */
data class IndexScan(
    val entries: List<IndexEntry>,
    val problems: List<String>,
)

/**
 * The need-keyed component index (`docs/components.md`), built from the sources by line scanning, the way
 * the catalog registry is: no Kotlin parser, so the same three tags and one regex port to another repository.
 *
 * A public component is a top-level `fun` with a capitalised name under `@Composable`, not `private` or
 * `internal`, not marked `@DesignSystemInternalApi`, and not named `…Preview`, `…Sample` or `…Demo`. Its KDoc carries, one per line:
 *
 * - `@need` the need in the reader's words ("pick one value from a long list");
 * - `@group` one of [IndexConfig.groups]' keys;
 * - `@replaces` (optional) what it saves a caller from building;
 * - `@sample` (optional) the catalog sample to copy, when the name does not follow `<Component>Sample`.
 *
 * The first KDoc sentence is the description column. Overloads each carry the tags; the index lists a name once.
 */
object ComponentIndex {
    private val declaration =
        Regex("""^((?:@\w+(?:\([^)]*\))?\s+)*)(public\s+)?(inline\s+)?fun\s+(?:<[^>]*>\s*)?(?:[\w<>?]+\.)?([A-Z]\w*)\s*\(""")
    private val hidden = Regex("""^(?:@\w+(?:\([^)]*\))?\s+)*(internal|private|protected)\s+""")
    private val tag = Regex("""^@(need|group|replaces|sample)\s+(\S.*)$""")
    private val excludedSuffixes = listOf("Preview", "Sample", "Demo")

    /** A helper: a class, object or interface, or a function that is not a capitalised composable. Group 1 is its name. */
    private val helperType =
        Regex(
            """^((?:@\w+(?:\([^)]*\))?\s+)*)(?:public\s+)?(?:(?:data|sealed|enum|abstract|open|value|fun|annotation)\s+)*(?:class|object|interface)\s+(\w+)""",
        )
    private val helperFun =
        Regex("""^((?:@\w+(?:\([^)]*\))?\s+)*)(?:public\s+)?(?:inline\s+)?fun\s+(?:<[^>]*>\s*)?(?:[\w<>?]+\.)?(\w+)\s*\(""")

    fun scan(
        fileName: String,
        source: String,
        config: IndexConfig = IndexConfig(),
    ): IndexScan {
        val lines = source.lines()
        val entries = mutableListOf<IndexEntry>()
        val problems = mutableListOf<String>()
        for ((index, line) in lines.withIndex()) {
            if (hidden.containsMatchIn(line)) continue
            val component = declaration.find(line)
            val helper = if (component == null && config.includeHelpers) helperMatch(line) else null
            if (component == null && helper == null) continue
            val name = component?.groupValues?.get(4) ?: helper!!.second
            val inline = component?.groupValues?.get(1) ?: helper!!.first
            if (component != null) {
                if (excludedSuffixes.any { name.endsWith(it) }) continue
                // A public component must be tagged. A helper is listed only when it chooses to be.
            }
            val above = SampleScanner.annotationsAbove(lines, index)
            // Shared between the design system's own modules, not offered to an app: not a component to look up by need.
            if (above.any { it.startsWith("@DesignSystemInternalApi") } || "@DesignSystemInternalApi" in inline) continue
            val composable = above.any { it.startsWith("@Composable") } || "@Composable" in inline
            if (component != null && !composable) continue
            if (helper != null && composable && name.first().isUpperCase()) continue
            val where = "$fileName:${index + 1}"
            val kdoc = SampleScanner.kdocAbove(lines, index - above.size)
            val tags = kdoc.mapNotNull { tag.find(it) }.associate { it.groupValues[1] to it.groupValues[2].trim() }
            val need = tags["need"]
            val groupKey = tags["group"]
            // A helper with no @need is not in the index, and is no problem.
            if (helper != null && need == null) continue
            val group = config.groups.firstOrNull { it.key == groupKey }
            when {
                need == null || groupKey == null ->
                    problems +=
                        "$where: public $name has no ${listOfNotNull(
                            "@need".takeIf { need == null },
                            "@group".takeIf { groupKey == null },
                        ).joinToString(" or ")} in its KDoc"
                group == null ->
                    problems += "$where: $name has unknown @group '$groupKey'; use one of ${config.groups.joinToString { it.key }}"
                else -> entries += IndexEntry(
                    name = name,
                    group = group,
                    need = need,
                    replaces = tags["replaces"],
                    description = SampleScanner.firstSentence(kdoc),
                    sample = tags["sample"],
                    module = fileName.substringBefore('/', missingDelimiterValue = ""),
                )
            }
        }
        return IndexScan(entries, problems)
    }

    /** The annotations on the line, then the helper's name, or null for a line that is not a helper. */
    private fun helperMatch(line: String): Pair<String, String>? =
        helperType.find(line)?.let { it.groupValues[1] to it.groupValues[2] }
            ?: helperFun.find(line)?.let { it.groupValues[1] to it.groupValues[2] }

    /** The sample to copy for [name]: its `@sample` tag, else `<name>Sample`, else the first `<name>…Sample`. */
    fun sampleFor(entry: IndexEntry, samples: Set<String>): String? =
        entry.sample
            ?: "${entry.name}Sample".takeIf { it in samples }
            ?: samples.filter { it.startsWith(entry.name) }.minOrNull()

    /** Every problem the sources have, as lines; empty when the index can be written. */
    fun problems(
        sources: List<Pair<String, String>>,
        catalogSources: List<Pair<String, String>>,
        config: IndexConfig = IndexConfig(),
    ): List<String> {
        val samples = sampleNames(catalogSources, config)
        val scans = sources.sortedBy { it.first }.map { (path, text) -> scan(path, text, config) }
        val unknownSamples = scans
            .flatMap { it.entries }
            .filter { it.sample != null && it.sample !in samples }
            .map { "${it.name}: @sample ${it.sample} is not a catalog sample" }
        return scans.flatMap { it.problems } + unknownSamples
    }

    fun render(
        sources: List<Pair<String, String>>,
        catalogSources: List<Pair<String, String>>,
        config: IndexConfig = IndexConfig(),
    ): String {
        val samples = sampleNames(catalogSources, config)
        val entries = sources
            .sortedBy { it.first }
            .flatMap { (path, text) -> scan(path, text, config).entries }
            .distinctBy { it.name to it.need }
        return buildString {
            config.generatedNote.forEach { appendLine(it) }
            appendLine()
            appendLine("# ${config.title}")
            appendLine()
            config.intro.forEach { appendLine(it) }
            for (group in config.groups) {
                val rows = entries.filter { it.group == group }.sortedWith(compareBy({ it.need.lowercase() }, { it.name }))
                if (rows.isEmpty()) continue
                appendLine()
                appendLine("## ${group.heading}")
                appendLine()
                val module = if (config.moduleColumn) " Module |" else ""
                appendLine("| Need | Component | What it is | Sample | Replaces |$module")
                appendLine("| --- | --- | --- | --- | --- |" + if (config.moduleColumn) " --- |" else "")
                for (row in rows) {
                    val sample = sampleFor(row, samples)?.let { "`$it`" } ?: "—"
                    val moduleCell = if (config.moduleColumn) " ${cell(row.module.ifEmpty { "—" })} |" else ""
                    appendLine(
                        "| ${cell(
                            row.need,
                        )} | `${row.name}` | ${cell(row.description)} | $sample | ${cell(row.replaces ?: "—")} |$moduleCell",
                    )
                }
            }
        }
    }

    private fun sampleNames(catalogSources: List<Pair<String, String>>, config: IndexConfig): Set<String> =
        when (config.sampleKind) {
            SampleKind.Functions ->
                catalogSources
                    .flatMap { (path, text) -> SampleScanner.scan(path, text).declared }
                    .filter { it.kind == EntryKind.Sample }
                    .map { it.function }
                    .toSet()
            SampleKind.Classes ->
                catalogSources.flatMap { (_, text) -> classDeclaration.findAll(text).map { it.groupValues[1] }.toList() }.toSet()
        }

    private val classDeclaration = Regex("""(?m)^\s*(?:(?:public|internal|private|data|open|abstract|final)\s+)*class\s+(\w+)""")

    private fun cell(text: String): String = text.replace("|", "\\|")
}

/**
 * `write <output> <root>…` writes the index; `check <output> <root>…` fails if the file differs or a public
 * composable is untagged. A root is `src=<dir>` (composable sources) or `catalog=<dir>` (samples).
 */
fun main(args: Array<String>) {
    val mode = args.getOrNull(0)
    val output = File(args.getOrNull(1) ?: usage())

    fun kotlinFiles(prefix: String) =
        args
            .drop(2)
            .filter { it.startsWith("$prefix=") }
            .map { File(it.substringAfter('=')) }
            .flatMap { root ->
                root
                    .walkTopDown()
                    .filter { it.isFile && it.extension == "kt" }
                    .map { it.relativeTo(root.parentFile).invariantSeparatorsPath to it.readText() }
                    .toList()
            }
    val sources = kotlinFiles("src")
    val catalog = kotlinFiles("catalog")
    val problems = ComponentIndex.problems(sources, catalog)
    if (problems.isNotEmpty()) {
        System.err.println("The component index cannot be built:\n" + problems.joinToString("\n") { "  $it" })
        exitProcess(1)
    }
    val rendered = ComponentIndex.render(sources, catalog)
    when (mode) {
        "write" -> output.apply { parentFile.mkdirs() }.writeText(rendered)
        "check" -> if (!output.exists() || output.readText() != rendered) {
            System.err.println("${output.path} is stale. Run ./gradlew generateComponentIndex and commit the result.")
            exitProcess(1)
        }
        else -> usage()
    }
}

private fun usage(): Nothing {
    System.err.println("usage: write|check <output> src=<dir>… catalog=<dir>…")
    exitProcess(2)
}
